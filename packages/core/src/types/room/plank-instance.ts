/**
 * Описание одной экземплярной доски пола.
 *
 * @remarks
 * Используется для построения `InstancedMesh`: каждая доска задаётся
 * позицией, поворотом и масштабом относительно базовой геометрии.
 *
 * @public
 * @type
 */
export type PlankInstance = {
  /**
   * Позиция центра доски по оси X.
   *
   * @public
   * @member
   */
  x: number;

  /**
   * Позиция центра доски по оси Z.
   *
   * @public
   * @member
   */
  z: number;

  /**
   * Поворот доски вокруг оси Y в радианах.
   *
   * @public
   * @member
   */
  rotation: number;

  /**
   * Масштаб доски по локальной оси X.
   *
   * @remarks
   * Используется, например, для подрезки крайних досок в прямой раскладке.
   *
   * @public
   * @member
   */
  scaleX: number;

  /**
   * Масштаб доски по локальной оси Z.
   *
   * @remarks
   * Используется для изменения фактической ширины экземпляра доски.
   *
   * @public
   * @member
   */
  scaleZ: number;
};
